def svg(path):
    text=Path(path).read_text(encoding='utf-8')
    text=re.sub(r'font-family:[^;}]+','font-family:MSJH',text)
    text=re.sub(r'font-family="[^"]+"','font-family="MSJH"',text)
    drawing=svg2rlg(io.BytesIO(text.encode('utf-8')))
    # svglib's family resolver can silently substitute Helvetica for a TTC.
    # Assign the embedded CJK font on the resulting vector text objects too.
    def fonts(node):
        if hasattr(node,'text'):node.fontName='MSJH-B' if node.fontSize>=20 else 'MSJH'
        for child in getattr(node,'contents',[]):fonts(child)
    fonts(drawing)
    return drawing
